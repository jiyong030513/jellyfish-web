def 설문위치_보정():
    g = pd.read_csv(P("02_시군.csv"), encoding=ENC)
    add = [r for r in 새_시군 if r[0] not in set(g["시군ID"])]
    if add:
        g = pd.concat([g, pd.DataFrame(add, columns=g.columns)], ignore_index=True)
        g.to_csv(P("02_시군.csv"), index=False, encoding=ENC, lineterminator="\n")
    p = pd.read_csv(P("09_설문지점.csv"), encoding=ENC, dtype={"시군ID": "Int64"})
    for jid, (sid, lat, lon, how) in 지점_보정.items():
        m = p["지점ID"] == jid
        assert m.sum() == 1, jid
        p.loc[m, ["시군ID", "위도", "경도", "좌표방법"]] = [sid, lat, lon, how]
    p.to_csv(P("09_설문지점.csv"), index=False, encoding=ENC, lineterminator="\n")
    print(f"[규칙 2] 시군 {len(add)}곳 추가, 설문 지점 {len(지점_보정)}곳 좌표·시군 보정")

