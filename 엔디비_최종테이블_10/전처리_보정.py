"""
전처리 보정 규칙 (정제 CSV에 한 번 적용하는 보정. 여러 번 실행해도 결과가 같음)

규칙 1. 수온 이상값: 같은 관측소의 앞·뒤 주 수온과 모두 5℃ 넘게 차이 나고,
        앞뒤 주 평균과 8℃ 넘게 차이 나는 주간 수온은 측정 오류로 보고 결측(빈칸) 처리
        (해당: 포항 22106, 2018-12-10 주 수온 1.8℃ → 앞뒤 주 15.5·16.2℃)
규칙 1-2. 원자료(시간별)로 확인한 부이 고장 구간의 주간 수온 결측 처리
        (포항 22106 2018-12-09 수온 −2.0~9.8℃가 2018-12-03 주(W02169) 평균에 섞임. 12/7~8 기록 없음)
규칙 1-3. 습도 이상값: 10% 미만 주간 습도는 측정 오류로 보고 결측 처리 (덕적도 2023-07-03 주 2.5%)
규칙 2. 설문 위치 좌표·시군 보정: 시군 테이블에 없던 시군 4곳을 추가하고,
        좌표가 없거나 잘못 매칭된 설문 지점 15곳의 좌표·시군을 수동으로 지정
        (좌표는 지명 기준 근사값. 반경 30km 계산에는 충분한 정밀도)

사용법: 이 파일을 CSV들과 같은 폴더에 두고 python 전처리_보정.py  →  load_db.py 실행 전에 1회
"""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
P = lambda f: os.path.join(HERE, f)
ENC = "utf-8-sig"

# ---------------- 규칙 1: 수온 이상값 ----------------
def 수온_이상값_결측처리():
    df = pd.read_csv(P("05_관측자료.csv"), encoding=ENC, dtype=str, keep_default_na=False)
    t = pd.to_numeric(df["수온"], errors="coerce")
    df["_t"] = t
    df = df.sort_values(["관측소ID", "시작일"])
    g = df.groupby("관측소ID")["_t"]
    prev, nxt = g.shift(1), g.shift(-1)
    bad = ((df["_t"] - prev).abs() > 5) & ((df["_t"] - nxt).abs() > 5) & ((df["_t"] - (prev + nxt) / 2).abs() > 8)
    ids = df.loc[bad, "관측ID"].tolist()
    df.loc[bad, "수온"] = ""
    # 규칙 1-2. 원자료(시간별)로 확인한 부이 고장 구간
    #   포항 22106 2018-12-09 수온 −2.0~9.8℃ → 2018-12-03 주(W02169) 평균에 섞임
    고장_주 = ["W02169", "W02170"]
    ids += [i for i in 고장_주 if i not in ids and df.loc[df["관측ID"] == i, "수온"].ne("").any()]
    df.loc[df["관측ID"].isin(고장_주), "수온"] = ""
    # 규칙 1-3. 습도 10% 미만은 측정 오류
    h = pd.to_numeric(df["습도"], errors="coerce")
    hid = df.loc[h < 10, "관측ID"].tolist()
    df.loc[h < 10, "습도"] = ""
    df = df.drop(columns="_t").sort_values("관측ID")
    df.to_csv(P("05_관측자료.csv"), index=False, encoding=ENC, lineterminator="\n")
    print(f"[규칙 1] 수온 이상값·고장 구간 결측 처리: {ids if ids else '해당 없음(이미 처리됨)'}")
    print(f"[규칙 1-3] 습도 이상값 결측 처리: {hid if hid else '해당 없음(이미 처리됨)'}")

